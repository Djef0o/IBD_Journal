package fr.ibdjournal.app.data.local

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor

@Database(
    entities = [
        MealEntity::class,
        StoolEntity::class,
        ProductEntity::class,
        ProfileEntity::class,
        MedicationEntity::class,
        CheckupEntity::class,
        LabResultEntity::class,
        DoseLogEntity::class,
        ExamEntity::class,
    ],
    version = 8,
    exportSchema = false,
)
@ConstructedBy(AppDatabaseConstructor::class)
abstract class AppDatabase : RoomDatabase() {
    abstract fun mealDao(): MealDao
    abstract fun stoolDao(): StoolDao
    abstract fun productDao(): ProductDao
    abstract fun profileDao(): ProfileDao
    abstract fun medicationDao(): MedicationDao
    abstract fun checkupDao(): CheckupDao
    abstract fun labResultDao(): LabResultDao
    abstract fun doseLogDao(): DoseLogDao
    abstract fun examDao(): ExamDao

    companion object {
        const val NAME = "ibd_diary.db"
    }
}

/** Implementation generated by Room for each platform. */
@Suppress("KotlinNoActualForExpect")
expect object AppDatabaseConstructor : RoomDatabaseConstructor<AppDatabase> {
    override fun initialize(): AppDatabase
}
